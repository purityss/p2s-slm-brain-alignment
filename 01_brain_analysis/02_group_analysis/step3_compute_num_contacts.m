    sem_region_numbers(i) = sum(strcmp(start_sem_regions, unique_all_regions{i}));
end
region_counts(:,4) = num2cell(sem_region_numbers); % Store in the 4th column

% ---- Count the number of electrodes in `start_both_contacts_p` ----
