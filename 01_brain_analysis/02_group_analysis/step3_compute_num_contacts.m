region_counts = cell(length(unique_all_regions), 6); 
region_counts(:,1) = unique_all_regions; % First column: brain region names

% **4️⃣ Count the number of electrodes in each brain region for each variable**
% ---- Count the number of electrodes in `all_sub_resp_contacts` ----
all_region_numbers = zeros(length(unique_all_regions), 1);
for i = 1:length(unique_all_regions)
    all_region_numbers(i) = sum(strcmp(all_regions, unique_all_regions{i}));
end
region_counts(:,2) = num2cell(all_region_numbers); % Store in the 2nd column

