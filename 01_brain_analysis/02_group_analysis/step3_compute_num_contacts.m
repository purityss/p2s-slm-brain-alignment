region_nums = zeros(size(region_counts,1), 5);

for c = 2:6
    for i = 1:size(region_counts,1)
        region_nums(i,c-1) = double(region_counts{i,c});
    end
end

% region_nums column 1 = all responsive contacts
% region_nums column 2 = phonology-only contacts
% region_nums column 3 = semantic-only contacts
% region_nums column 4 = both_p contacts
% region_nums column 5 = both_s contacts

num_all_p_s = zeros(length(macro_region_names), 4);
matched_flag = false(size(region_names));

for r = 1:length(macro_region_names)

    sub_regions = macro_region_defs{r};

    idx = ismember(region_names, sub_regions);
    matched_flag = matched_flag | idx;

    num_all_p_s(r,1) = sum(region_nums(idx,1));
    num_all_p_s(r,2) = sum(region_nums(idx,2));
    num_all_p_s(r,3) = sum(region_nums(idx,3));

    % both_p and both_s usually represent the same both-selective contacts.
    % Using their sum may double-count the same contacts.
    both_p_count = sum(region_nums(idx,4));
    both_s_count = sum(region_nums(idx,5));

    if both_p_count ~= both_s_count
        warning('%s: both_p and both_s counts are inconsistent. Please check whether a union should be used.', macro_region_names{r});
    end

    num_all_p_s(r,4) = max(both_p_count, both_s_count);

end

